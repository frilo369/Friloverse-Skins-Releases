// Copy FrYiLoCo's party icon code and catalogue from the sibling checkout.
// Summoner artwork is not bundled: the app reads it from the installed League.
import {copyFile,mkdir,readFile,rm,writeFile} from 'node:fs/promises';
import path from 'node:path';

const source=process.argv[2]||'C:/FriloCode/FrYiLoCo Skins/desktop-ui';
const ui=path.resolve('src/ui');
const read=name=>readFile(path.join(source,name),'utf8');

function plain(code){
  return code.replace(/^import .*\r?\n/gm,'').replace(/^export (function|const) /gm,'$1 ');
}
function without(code,name){
  const start=code.search(new RegExp(`^(?:/\\*\\*.*\\r?\\n)?export function ${name}\\(`,'m'));
  if(start<0)throw new Error(`FrYiLoCo no longer has ${name}.`);
  const end=code.slice(start).search(/^}\r?\n/m);
  return code.slice(0,start)+code.slice(start+end).replace(/^}\r?\n/,'');
}
const parts=await Promise.all(['esports-team-icons.mjs','party-icons.mjs','local-icons.mjs'].map(read));
parts[1]=without(without(parts[1],'summonerIconCandidates'),'deduplicatePartyIcons');
const names=['PARTY_ICON_CATEGORIES','isEsportsTeamIcon','recentPartyIcons','partyIconSections','partyIconsFromLocalCatalogue','advancePartyIconFallback'];
const body=parts.map(plain).join('\n').replaceAll("'/party-icon-unavailable.svg'","'party-icon-unavailable.svg'");
await writeFile(path.join(ui,'party-icons.js'),`// Generated by scripts/sync-party-icons.mjs from FrYiLoCo; edit it there.
(()=>{
${body}
globalThis.FriloversePartyIcons={${names.join(',')}};
})();
`);

const manifest=JSON.parse(await read('public/party-icons.json'));
const folder=path.join(ui,'arena-icons');
await rm(folder,{recursive:true,force:true});await mkdir(folder,{recursive:true});
await mkdir(path.join(ui,'party-icons'),{recursive:true});
const icons=[];
for(const {id,summonerId,name,category,path:file,rarity,year,firstPatch} of manifest.icons){
  const local=summonerId===undefined;
  if(local)await copyFile(path.join(source,'public',file),path.join(ui,file));
  icons.push({id,...(summonerId===undefined?{}:{summonerId}),name,category,path:local?file.replace(/^\//,''):file,
    ...(rarity===undefined?{}:{rarity}),...(year===undefined?{}:{year}),...(firstPatch===undefined?{}:{firstPatch})});
}
await writeFile(path.join(ui,'party-icons.json'),JSON.stringify({aliases:manifest.aliases,icons}));
await copyFile(path.join(source,'public','party-icon-unavailable.svg'),path.join(ui,'party-icon-unavailable.svg'));
console.log(`Copied ${icons.length} party icons, ${icons.filter(icon=>icon.summonerId===undefined).length} of them bundled.`);
